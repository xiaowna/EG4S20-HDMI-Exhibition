"""Embed the V04 clock menu font, preserving all original 64 slots."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
CHARACTERS = ''.join(dict.fromkeys(
    ' 播放设置亮度对比切图渐变音频波形自动轮开启关闭左右调节确认下项返回产品演示0123456789+-./%K←→彩色谱背景乐:'))


def main():
    path = Path('C:/Windows/Fonts/simhei.ttf')
    font = ImageFont.truetype(str(path), 16)
    glyphs, words = [], []
    assert len(CHARACTERS) <= 64
    clock_characters='时间保存写入成功失败'
    characters=CHARACTERS+'\0'+clock_characters
    note_first=len(characters)
    note=Image.new('L',(64,64));draw=ImageDraw.Draw(note)
    draw.ellipse((11,40,29,53),fill=255)
    draw.rectangle((26,10,30,46),fill=255)
    draw.polygon([(30,10),(47,18),(47,30),(42,23),(30,20)],fill=255)
    for ch in characters:
        tile = Image.new('1', (16, 16))
        if ch!='\0':
            ImageDraw.Draw(tile).text(((16-round(font.getlength(ch)))//2, 0), ch, font=font, fill=1)
        rows = [''.join(str(int(tile.getpixel((x, y)) != 0)) for x in range(16)) for y in range(16)]
        value = sum(int(bit) << (y*16+x) for y, row in enumerate(rows) for x, bit in enumerate(row))
        assert value or ch in (' ','\0'), f'Missing glyph {ch}'
        glyphs.append({'character': ch, 'rows': rows})
        words.append(value)
    # Eight rotating note poses occupy previously zero slots in bank 2.
    # Keep every pre-existing glyph and the native synchronous ROM unchanged.
    for phase in range(8):
        rotated=note.rotate(-45*phase,resample=Image.Resampling.BICUBIC).resize((16,16),Image.Resampling.LANCZOS)
        rows=[''.join(str(int(rotated.getpixel((x,y))>=96)) for x in range(16)) for y in range(16)]
        glyphs.append({'character':chr(0xe100+phase),'rows':rows})
        words.append(sum(int(bit)<<(y*16+x) for y,row in enumerate(rows) for x,bit in enumerate(row)))
    characters+=''.join(chr(0xe100+i) for i in range(8))
    words += [0] * (128-len(words))
    constants = ',\n'.join(f"  256'h{word:064x}" for word in reversed(words))
    rtl = '''// Generated by tools/generate_settings_font.py. Optional 128 x 16 x 16 clock font.
// The project retains gate eram_init=on through syn_1 more options.
module settings_font_rom #(parameter CLOCK_FONT=0)(input wire clk,input wire [14:0] address,output wire pixel);
 localparam [32767:0] FONT={
''' + constants + '''};
 // Explicit native 4096x2 banks keep the address bits unmodified at BRAM.
 // Both RAM data and the bank/bit selector register on the same edge:
 // selecting their outputs adds no second pixel-clock stage.
 localparam BANKS=CLOCK_FONT?4:2;
 localparam SELECT_BITS=CLOCK_FONT?3:2;
 wire [BANKS*2-1:0] pairs;
 genvar b;
 generate for(b=0;b<BANKS;b=b+1)begin:bank
  (* rom_style="bram" *) reg [1:0] memory[0:4095];
  reg [1:0] q;integer i;
  initial for(i=0;i<4096;i=i+1)memory[i]=FONT[b*8192+i*2+:2];
  always @(posedge clk)q<=memory[address[12:1]];
  assign pairs[b*2+:2]=q;
 end endgenerate
 reg [SELECT_BITS-1:0] select_q;
 always @(posedge clk)
  if(CLOCK_FONT)select_q<={address[14:13],address[0]};
  else select_q<={address[13],address[0]};
 assign pixel=pairs[select_q];
endmodule
'''
    (ROOT/'rtl/settings_font_rom.v').write_text(rtl, encoding='utf-8')
    manifest = {'characters': characters, 'font': path.name,
                'font_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                'glyphs': glyphs, 'size': [16, 16], 'slots': 128,
                'music_note_first':note_first,'music_note_frames':8}
    (ROOT/'assets/settings_v04.json').write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(f'Generated V04: {len(glyphs)} glyphs; original 64 slots preserved')


if __name__ == '__main__':
    main()
