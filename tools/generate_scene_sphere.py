"""Sample circular latitude/longitude curves into one native RAM32K."""
from pathlib import Path
import hashlib,json,math
ROOT=Path(__file__).resolve().parents[1]

def main():
    points=[tuple(round(v) for v in (32*math.cos(math.radians(lat))*math.cos(2*math.pi*n/32),
             32*math.sin(math.radians(lat)),32*math.cos(math.radians(lat))*math.sin(2*math.pi*n/32)))
             for lat in [67.5,45,22.5,0,-22.5,-45,-67.5] for n in range(32)]+[(0,32,0),(0,-32,0)]
    packed=[sum((v&255)<<(8*i) for i,v in enumerate(p)) for p in points]+[0]*30
    native=sum(v<<(32*i) for i,v in enumerate(packed))
    logical=sum(v<<(24*i) for i,v in enumerate(packed))
    params=',\n  '.join(f".INIT_{n:02X}(256'h{(native>>(256*n))&((1<<256)-1):064x})" for n in range(128))
    source=f'''// Generated by tools/generate_scene_sphere.py. 226 Q5 XYZ sphere vertices.
module scene_sphere_rom(input wire clk,input wire [7:0] address,
 output wire signed [7:0] x,y,z);
 wire [23:0] data;
`ifdef __ICARUS__
 localparam [6143:0] DATA=6144'h{logical:01536x};
 reg [23:0] memory[0:255];reg [23:0] q;integer i;
 initial for(i=0;i<256;i=i+1)memory[i]=DATA[i*24+:24];
 always @(posedge clk)q<=memory[address];
 assign data=q;
`else
 wire [15:0] low_word,high_word;
 EG_PHY_BRAM32K #(.MODE("DP16K"),.DATA_WIDTH_A("16"),.DATA_WIDTH_B("16"),
  .REGMODE_A("NOREG"),.REGMODE_B("NOREG"),.WRITEMODE_A("NORMAL"),.WRITEMODE_B("NORMAL"),
  {params}) storage(
  .doa(low_word),.dia(16'd0),.addra({{2'd0,address,1'b0}}),
  .bytea(1'b0),.bytewea(1'b0),.csa(1'b1),.wea(1'b0),.clka(clk),.rsta(1'b0),.ocea(1'b1),
  .dob(high_word),.dib(16'd0),.addrb({{2'd0,address,1'b1}}),
  .byteb(1'b0),.byteweb(1'b0),.csb(1'b1),.web(1'b0),.clkb(clk),.rstb(1'b0),.oceb(1'b1));
 assign data={{high_word[7:0],low_word}};
`endif
 assign x=data[7:0];assign y=data[15:8];assign z=data[23:16];
endmodule
'''
    (ROOT/'rtl/scene_sphere_rom.v').write_text(source,encoding='utf-8')
    (ROOT/'assets/scene_sphere.json').write_text(json.dumps(dict(vertices=points,packed_words=packed,
        latitude_samples=7,longitude_samples=32,earth_meridians=16,moon_meridians=8,
        native_blocks=1,generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()),separators=(',',':'))+'\n',encoding='utf-8')
    print('Generated 226 circular sphere vertices, one RAM32K')

if __name__=='__main__':main()
