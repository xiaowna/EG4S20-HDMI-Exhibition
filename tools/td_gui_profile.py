STAGES=[('read_design',GATE),('opt_rtl',GATE),('opt_gate',GATE),
        ('opt_place',PLACE),('opt_route',ROUTE),('bitgen',BITGEN)]

def patch(text):
    """Keep all vendor/custom code outside our own marked zone prefixes."""
    changed=0
    for stage,body in STAGES:
        anchor='### Editable zone for '+stage+' ###\n'
        if anchor not in text:continue
        if text.count(anchor)!=1:raise ValueError('Ambiguous TD flow zone: '+stage)
        snippet='  # '+MARK+' '+stage+' BEGIN\n'+body+'  # '+MARK+' '+stage+' END\n'
        expression=re.escape(anchor)+r'(?:  # '+MARK+' '+stage+r' BEGIN\n.*?  # '+MARK+' '+stage+r' END\n)?'
        text,n=re.subn(expression,lambda _:anchor+snippet,text,count=1,flags=re.S)
        changed+=n
    if changed<3:raise ValueError('Unsupported TD flow script')
    return text

def project_tcl():
    result='# Project-scoped TD GUI profile; generated by td_gui_profile.py.\n'
    for stage,body in STAGES:
        if stage=='read_design':
            body+=ROM_SOURCE
        if stage=='bitgen':
            body=body.replace('set hdmi_checked_root [pwd]','set hdmi_checked_root $hdmi_root')
        receipt='''  set hdmi_receipt [open .hdmi_gui_STAGE.profile w]
  puts $hdmi_receipt [list stage STAGE root $hdmi_root checked_at [clock seconds]]
  close $hdmi_receipt
'''.replace('STAGE',stage)
        result+='proc hdmi_gui_'+stage+' {prj_name hdmi_root} {\n'+body+receipt+'}\n'
    return result

def dispatch(stage):
    # TD regenerates local run scripts on launch. Its shared template must only
    # dispatch for this named project with the explicit project-owned helper.
    return f'''  # {DISPATCH} {stage} BEGIN
  if {{$prj_name eq "HDMI_media_board_WAV"}} {{
    set hdmi_scan [pwd]
    for {{set hdmi_i 0}} {{$hdmi_i<8 && ![file isfile [file join $hdmi_scan .hdmi_gui_root.txt]]}} {{incr hdmi_i}} {{
      set hdmi_scan [file dirname $hdmi_scan]
    }}
{MISSING_ROOT}    if {{[file isfile [file join $hdmi_scan .hdmi_gui_root.txt]]}} {{
      set hdmi_ch [open [file join $hdmi_scan .hdmi_gui_root.txt] r]
      set hdmi_root [string trim [read $hdmi_ch]]
      close $hdmi_ch
      if {{![file isfile [file join $hdmi_root tools td_gui_profile.tcl]] || ![file isfile [file join $hdmi_root HDMI_media_board_WAV.al]]}} {{error "HDMI GUI profile root is stale; reopen with the project launcher"}}
      source [file join $hdmi_root tools td_gui_profile.tcl]
      hdmi_gui_{stage} $prj_name $hdmi_root
    }}
  }}
  # {DISPATCH} {stage} END
'''

def remove_dispatch(raw):
    for stage,_ in STAGES:
        current=dispatch(stage)
        # Accept only the exact installed V1 block and its fail-closed upgrade.
        blocks=[text.encode('utf-8') for text in (current,current.replace(MISSING_ROOT,'',1))]
        if b'\r\n' in raw:blocks=[block.replace(b'\n',b'\r\n') for block in blocks]
        if sum(raw.count(block) for block in blocks)>1:raise ValueError('Duplicate GUI template dispatch')
        for block in blocks:raw=raw.replace(block,b'')
    if DISPATCH.encode() in raw:raise ValueError('Unknown modified GUI template dispatch')
    return raw

def template_patch(raw,template):
    base=remove_dispatch(raw)
    if template=='MultiSeed.tcl':
        if __package__:
            from .fix_td_multiseed import patched_script
        else:
            from fix_td_multiseed import patched_script
        base=patched_script(base)
    elif hashlib.sha256(base).hexdigest()!=DEFAULT_SHA:
        raise ValueError('Unknown TD DefaultFlow.tcl version; no file was changed')
    text=base.decode('utf-8-sig').replace('\r\n','\n')
    for stage,_ in STAGES:
        anchor='### Editable zone for '+stage+' ###\n'
        if anchor in text:text=text.replace(anchor,anchor+dispatch(stage),1)
    return text.replace('\n','\r\n').encode('utf-8') if b'\r\n' in base else text.encode('utf-8')

def install(root,td=TD):
    root=Path(root)
    stamp=datetime.datetime.now().strftime('%Y%m%d_%H%M%S_%f')
    # Validate both vendor files before writing either of them.
    changes=[]
    for name in ['DefaultFlow.tcl','MultiSeed.tcl']:
        p=Path(td)/'doc/scripts'/name;raw=p.read_bytes()
        changes.append((p,raw,template_patch(raw,name)))
    (root/'tools/td_gui_profile.tcl').write_text(project_tcl(),encoding='utf-8')
    run_root=root/'HDMI_media_board_WAV_Runs';run_root.mkdir(exist_ok=True)
    (run_root/'.hdmi_gui_root.txt').write_text(root.resolve().as_posix()+'\n',encoding='utf-8')
    for p,raw,updated in changes:
        if updated==raw:continue
        backup=root/'reports/td_gui_profile_backups'/stamp/p.name
        backup.parent.mkdir(parents=True,exist_ok=True);backup.write_bytes(raw)
        p.write_bytes(updated)
        if p.read_bytes()!=updated:raise OSError('TD template readback mismatch')
    check_installed(root,td)

def check_source(root):
    p=Path(root)/'tools/td_gui_profile.py'
    if not p.is_file() or hashlib.sha256(p.read_bytes()).digest()!=hashlib.sha256(Path(__file__).read_bytes()).digest():
        raise ValueError('GUI profile installer is missing or differs from the checker')
    p=Path(root)/'tools/td_gui_profile.tcl'
    if not p.is_file() or p.read_text(encoding='utf-8-sig')!=project_tcl():
        raise ValueError('Project GUI profile helper is missing or altered')

def check_installed(root,td=TD):
    p=Path(root)/'tools/td_gui_profile.tcl'
    if not p.is_file() or p.read_text(encoding='utf-8-sig')!=project_tcl():
        raise ValueError('Project GUI helper missing or altered; run td_gui_profile.py --install')
    p=Path(root)/'HDMI_media_board_WAV_Runs/.hdmi_gui_root.txt'
    if not p.is_file() or p.read_text(encoding='utf-8').strip()!=Path(root).resolve().as_posix():
        raise ValueError('GUI run directory root pointer missing or stale')
    for name in ['DefaultFlow.tcl','MultiSeed.tcl']:
        p=Path(td)/'doc/scripts'/name;raw=p.read_bytes()
        if template_patch(raw,name)!=raw:raise ValueError('TD GUI dispatcher missing: '+str(p))

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
    p.add_argument('--install',action='store_true');a=p.parse_args()
    if a.install:install(a.root)
    else:check_installed(a.root)
    print('PASS project-owned TD GUI gate/place/route/timing profile')

if __name__=='__main__':main()
