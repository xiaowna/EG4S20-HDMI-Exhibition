"""Finite 3D sidebar: eight orbital periods and Earth/Moon controls in one RAM32K."""
from pathlib import Path
import hashlib,json
from PIL import Image,ImageDraw,ImageFont
from generate_intro_assets import rom_module

ROOT=Path(__file__).resolve().parents[1]

def main():
 config=ROOT/'assets/scene_periods.json';data=json.loads(config.read_text(encoding='utf-8'))
 font_path=Path('C:/Windows/Fonts/simhei.ttf')
 font=lambda size:ImageFont.truetype(str(font_path),size)
 image=Image.new('1',(128,256));draw=ImageDraw.Draw(image);rows=[]
 draw.text((36,0),'公转周期',font=font(14),fill=1)
 for i,planet in enumerate(data['planets']):
  period=f"{planet['years']*data['year_days']:.2f}天" if i<4 else f"{planet['years']:.2f}年"
  assert font(12).getlength(period)<=64
  draw.text((4,24+i*20),planet['name'],font=font(12),fill=1)
  draw.text((64,24+i*20),period,font=font(12),fill=1)
  rows.append(dict(name=planet['name'],display=period))
 draw.text((11,180),'KEY5 切换地月',font=font(10),fill=1)
 for y,text in [(192,'地月系统'),(208,f"月球公转 {data['moon_days']:.2f}天"),
                (224,'KEY7缩小 KEY8放大'),(240,'KEY5切换 KEY10归位')]:
  size=12 if y==192 else 10;f=font(size);assert f.getlength(text)<=128
  draw.text(((128-round(f.getlength(text)))//2,y),text,font=f,fill=1)
 # Labels share the existing read port and unused header margins, not a new ROM.
 draw.text((4,0),'太阳',font=font(12),fill=1)
 draw.text((4,192),'月球',font=font(12),fill=1)
 bits=[int(image.getpixel((x,y))!=0) for y in range(256) for x in range(128)]
 words=[sum(bits[n+j]<<j for j in range(16)) for n in range(0,32768,16)]
 rtl='// Generated by tools/generate_scene_sidebar.py; one synchronous native RAM32K.\n'+rom_module('scene_sidebar_word_rom',words,11)
 rtl+='''module scene_sidebar_rom(input wire clk,input wire [14:0] address,output wire pixel);
 wire [15:0] data;reg [3:0] select_q;
 scene_sidebar_word_rom storage(.clk(clk),.en(1'b1),.address(address[14:4]),.data(data));
 always @(posedge clk)select_q<=address[3:0];
 assign pixel=data[select_q];
endmodule
'''
 (ROOT/'rtl/scene_sidebar_rom.v').write_text(rtl,encoding='utf-8')
 (ROOT/'assets/scene_sidebar.json').write_text(json.dumps(dict(width=128,height=256,bits=bits,words=words,rows=rows,
  native_blocks=1,sources=data['sources'],config_sha256=hashlib.sha256(config.read_bytes()).hexdigest(),
  font_sha256=hashlib.sha256(font_path.read_bytes()).hexdigest()),ensure_ascii=False,separators=(',',':'))+'\n',encoding='utf-8')
 image.convert('RGB').save(ROOT/'assets/scene_sidebar_preview.png')
 print('Generated all 32768 sidebar bits in one native RAM32K:',rows)

if __name__=='__main__':main()
