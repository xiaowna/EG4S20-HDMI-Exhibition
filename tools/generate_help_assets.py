"""Compile four on-screen help pages into character and 16px glyph ROMs."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont
from generate_intro_assets import rom_module

ROOT = Path(__file__).resolve().parents[1]


def main():
    config = json.loads((ROOT / 'assets/help_pages.json').read_text(encoding='utf-8'))
    assert len(config['pages']) == 4
    grids = []
    for page in config['pages']:
        rows = [''] * 32
        rows[0] = page['title']
        assert len(page['lines']) == 10
        for i, line in enumerate(page['lines']):
            rows[2 + i * 2] = line
        rows[23] = config['footer']
        assert all(len(row) <= 32 for row in rows)
        grids.append(rows)
    # The homepage hint shares the fourth page's otherwise-unused row 31.
    grids[3][31] = config['home_hint']
    characters = ''.join(dict.fromkeys(' ' + ''.join(row for grid in grids for row in grid)))
    assert len(characters) <= 256
    font_path = Path('C:/Windows/Fonts/simhei.ttf')
    font = ImageFont.truetype(str(font_path), 16)
    glyphs = []
    for char in characters:
        image = Image.new('1', (16, 16))
        ImageDraw.Draw(image).text(((16 - round(font.getlength(char))) // 2, 0), char, font=font, fill=1)
        rows = [sum(int(image.getpixel((x, y)) != 0) << x for x in range(16)) for y in range(16)]
        assert any(rows) or char == ' '
        glyphs.append(rows)
    glyphs += [[0] * 16 for _ in range(256 - len(glyphs))]
    ids = [characters.index(char) for grid in grids for row in grid for char in row.ljust(32)]
    words = [ids[i] | (ids[i + 1] << 8) for i in range(0, len(ids), 2)]
    rtl = '// Generated by tools/generate_help_assets.py; text is in assets/help_pages.json.\n'
    rtl += rom_module('help_character_rom', words, 11)
    # Two explicit single-bank instances avoid adding a third ROM clock.
    for bank in range(2):
        rows = [row for glyph in glyphs[bank * 128:(bank + 1) * 128] for row in glyph]
        rtl += rom_module(f'help_glyph_bank{bank}', rows, 11)
    (ROOT / 'rtl/help_assets_rom.v').write_text(rtl, encoding='utf-8')
    manifest = dict(config=config, characters=characters, glyph_rows=glyphs, character_ids=ids,
                    font_sha256=hashlib.sha256(font_path.read_bytes()).hexdigest(), native_ram32k=3)
    (ROOT / 'assets/help_assets.json').write_text(json.dumps(manifest, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    print(f'Help ROM: {len(characters)} glyphs, four pages, three RAM32K blocks')


if __name__ == '__main__':
    main()
