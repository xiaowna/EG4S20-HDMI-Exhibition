"""Generate the fixed V01 subtitle ROM; normal FPGA builds need no font files."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TEXT = "仰望星空，探索宇宙，逐梦星河"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, default=Path('C:/Windows/Fonts/simsun.ttc'))
    args = parser.parse_args()
    if len(TEXT) != 14:
        raise ValueError('The existing subtitle window requires exactly 14 glyphs')
    font = ImageFont.truetype(str(args.font), 16)
    glyphs, words = [], []
    for ch in TEXT:
        image = Image.new('1', (16, 16))
        x = (16 - round(font.getlength(ch))) // 2
        ImageDraw.Draw(image).text((x, 0), ch, font=font, fill=1)
        fill = [[int(image.getpixel((x, y)) != 0) for x in range(16)] for y in range(16)]
        glyphs.append({'character': ch, 'rows': [''.join(map(str, row)) for row in fill]})
        value = 0
        for y in range(16):
            for x in range(16):
                outline = any(fill[yy][xx] for yy in range(max(0, y-1), min(16, y+2))
                              for xx in range(max(0, x-1), min(16, x+2)))
                pixel = 2 if fill[y][x] else int(outline)
                value |= pixel << (2 * (y * 16 + x))
        words.append(value)
    words += [0] * (16 - len(words))
    constants = ',\n'.join(f"  512'h{word:0128x}" for word in reversed(words))
    rtl = '''// Generated by tools/generate_subtitle_font.py. 0=transparent, 1=outline, 2=fill.
// 16 glyph slots x 16 rows x 16 columns x 2 bits = one 9Kbit BRAM.
// TD gate eram_init MUST be on; verify the routed INIT data before delivery.
module subtitle_font_rom(input wire clk,input wire [11:0] address,output wire [1:0] pixel);
 localparam [8191:0] FONT={
''' + constants + '''};
`ifdef __ICARUS__
 reg [1:0] glyphs[0:4095];
 integer i;
 initial for(i=0;i<4096;i=i+1)glyphs[i]=FONT[i*2+:2];
 reg [1:0] q;
 always @(posedge clk)q<=glyphs[address];
 assign pixel=q;
`else
 anlogic_initialized_rom #(.DATA(FONT)) storage(clk,address,pixel);
`endif
endmodule
'''
    (ROOT / 'rtl/subtitle_font_rom.v').write_text(rtl, encoding='utf-8')
    assets = ROOT / 'assets'
    assets.mkdir(exist_ok=True)
    manifest = {'text': TEXT, 'size': [16, 16], 'display_scale': 2,
                'font': args.font.name, 'font_sha256': hashlib.sha256(args.font.read_bytes()).hexdigest(),
                'glyphs': glyphs}
    (assets / 'subtitle_v01.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    preview = Image.new('RGB', (640, 112), '#203448')
    for slot, item in enumerate(glyphs):
        tile = Image.new('1', (16, 16))
        tile.putdata([int(v) for row in item['rows'] for v in row])
        preview.paste((255, 224, 64), (16+slot*32, 32), tile.resize((32, 32), Image.Resampling.NEAREST))
    preview.save(assets / 'subtitle_v01_font_preview.png')
    print(f'GENERATED V01 subtitle: {len(TEXT)} glyphs, 8192 ROM bits, no external runtime font dependency')


if __name__ == '__main__':
    main()
